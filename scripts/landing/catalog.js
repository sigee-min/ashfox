const withHrefFields = (entry) => {
  const slug = entry.slug || entry.outputFile.replace(/\.[^.]+$/, '');
  const thumbHref =
    entry.domain === 'sprite' || entry.domain === 'tile'
      ? `/media/catalog/${entry.outputFile}`
      : entry.domain === 'sound'
        ? `/media/catalog/${entry.waveFile}`
        : `/media/catalog/thumbs/${slug}.png`;
  return {
    ...entry,
    slug,
    sourceHref: `/${entry.sourcePath}`,
    outputHref: `/media/catalog/${entry.outputFile}`,
    thumbHref,
    specs: entry.specs || { en: '', ko: '' },
    meta: entry.meta || {},
  };
};

